    // ---------------- Astronomicals.xml: Venus cloud deck ----------------
    // The stock layer (VenusPlaceholderClouds) stays - its VenusCloud coverage texture and Earth's
    // cumulus detail tile, whose type channel picks stratus, cumulus or congestus from place to place -
    // but its five cloud types are replaced and the tile's coverage lifted. Stock has the types at
    // 10-45 km, each growing from the layer's floor, so stratus patches are 13 km-deep basins and
    // congestus cells towers, and where the tile has open sky the layer has holes to the bare
    // atmosphere. Venus's clouds are one deck (Pioneer Venus, Venera, Vega): lower cloud 48-50.5 km, the
    // densest; middle cloud to 56.5 km; upper cloud thinning to the tops, ~70 km.
    //
    // So every type here shares a solid base 48 -> ~70.5 km, and the stock variety lives only in short
    // crowns above it. VenusCloudDetail.png (make_venus_detail.py) is the Earth tile with its coverage
    // lifted to 0.7-1: the shader fills where coverage + shape - 1 > 0 and noise can only open it below
    // 0.65, so the base can no longer hole. The crowns rise over shape 0.3 -> 0, i.e. over that 0.7-1,
    // so their height still follows the tile's whole original coverage: stratus to 71.2 km, cumulus to
    // 71.6 km, congestus to 72 km. The engine draws the 2D layer at the layer's top (the highest type's
    // StartAltitude + Height), so the crowns stay under 72 km: seen from above the deck reaches optical
    // depth 1 at ~68.7 km and its edge at the limb at ~71 km (measured cloud tops ~70 km), where the
    // 2D layer takes over at 72 km. All five span 48-72 km and share one density profile: 3.5/km in
    // the lower cloud, 1.96/km in the middle, then 1.75/km at 57 km thinning with a 12 km scale height
    // (column optical depth ~30, measured 25-40). Stock noise scale, edge sharpness and scattering
    // brightness. ShadowBuilder.PatchVenusClouds swaps both, inside Venus's body only.
